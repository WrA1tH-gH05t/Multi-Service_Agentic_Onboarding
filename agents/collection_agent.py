"""
Collection Agent - Phase 2 & Phase 3

Module Purpose & Role in the Project:
-------------------------------------
The Collection Agent is a core reasoning component in the multi-stage document application
lifecycle. Rather than acting as a naive script requesting a flat list of documents sequentially,
it acts as a stateful reasoning machine tracking application readiness, handling interruptions,
detecting and routing allowed alternatives, managing failure retries, and escalating unreadable
submissions.

System Architecture & Cross-File Interconnections:
--------------------------------------------------
1. Upstream Callers:
   - `app/main.py`: Instantiates `CollectionAgent(repository=app_state["repository"])` and registers
     it into global application state `app_state["collection_agent"]`.
   - `app/routes/applications.py`: Calls `create_session()` when a user initiates a new application
     via `/applications/create`, binding service requirements from the service catalogue.
   - `app/routes/collection.py`: Calls `get_session()` to inspect status (`/collection/session/{session_id}`)
     and calls `submit_document()` (`/collection/session/{session_id}/submit`) when a user uploads
     a document payload processed by extraction services.
   - `app/routes/chat.py`: In the wizard chat interface (`/chat/wizard`), queries `get_session()`
     and `get_user_active_session()` to synchronize chat dialogue steps with collection progress.

2. Downstream Dependencies & External Services:
   - `services/repository.py` (`Repository`): The agent interacts directly with repository methods
     `save_collection_session()`, `get_collection_session()`, and `get_service()` to persist and restore
     state in PostgreSQL and look up service definitions and allowed document alternatives.
   - `services/database.py` (`DatabaseService` / `CollectionSession` ORM model): Underlying database layer
     storing sessions in the `collection_sessions` table with JSON columns for requirements, audit trails,
     and conversation context.
   - `agents/validation_agent.py` (`ValidationAgent`): When collection reaches completeness (`all_ok`),
     the application status transitions to `"complete"` so the Validation Agent or review endpoints
     can execute deep rule validation, cross-document matching, and threshold audits.
   - Document Extraction Services (`services/extraction_ladder.py`, `services/ocr.py`, `services/docling_service.py`):
     Extraction results (confidence, fields, extraction_ok flag) generated by these services are passed
     into `submit_document()`.

Design Decision:
----------------
Uses a state machine with reasoning steps, not a flat list. The agent tracks what's submitted
vs what's missing, reasons about alternatives, and handles mid-conversation interruptions without
losing state.
"""

from typing import Dict, List, Optional, Tuple, Set
from datetime import datetime, timezone
import uuid


def _utcnow() -> datetime:
    """
    Get the current timezone-aware UTC datetime.

    Role & Cross-File Usage:
        Provides consistent UTC timestamps for document submission tracking, failure logging,
        and state change timestamps stored across `ApplicationSession` and `DocumentRequirement`.

    Returns:
        datetime: Current UTC timestamp with timezone.utc info.
    """
    return datetime.now(timezone.utc)


class DocumentRequirement:
    """
    Represents a single document requirement for a service.

    Responsibility:
    ---------------
    Maintains the granular lifecycle and extraction state for an individual document slot
    (e.g., 'passport', 'national_id', 'driving_license') within an application session.

    State Attributes:
    -----------------
    doc_type (str): Unique document identifier/type name according to service configuration.
    mandatory (bool): Indicates if the document is strictly required or optional for the service.
    submitted (bool): Flag indicating whether a file has been uploaded for this requirement slot.
    submitted_file_id (Optional[str]): Storage identifier or UUID referencing the uploaded document asset.
    submitted_at (Optional[datetime]): Timestamp recording when the document was received.
    extraction_ok (bool): Boolean flag indicating whether text/field extraction was deemed acceptable.
    extraction_fields (Dict): Extracted key-value attributes (e.g., name, expiry_date, document_number).
    extraction_confidence (float): Confidence score (0.0 to 1.0) returned by extraction models.
    upload_failures (int): Counter tracking failed extraction attempts or unreadable uploads for this requirement.
    last_failure_reason (Optional[str]): Diagnostic message explaining why the latest attempt was rejected.

    Interactions:
    -------------
    Constructed and updated by `ApplicationSession`. Serialized via `to_dict()` for persistence into
    PostgreSQL JSON columns in the `collection_sessions` database table.
    """

    def __init__(self, doc_type: str, mandatory: bool = True):
        """
        Initialize a new document requirement.

        Args:
            doc_type (str): The document category/type identifier (e.g. 'passport', 'national_id').
            mandatory (bool, optional): Whether this document is required (True) or optional (False). Defaults to True.
        """
        self.doc_type = doc_type
        self.mandatory = mandatory
        self.submitted = False
        self.submitted_file_id: Optional[str] = None
        self.submitted_at: Optional[datetime] = None
        self.extraction_ok = False
        self.extraction_fields: Dict = {}
        self.extraction_confidence: float = 0.0
        self.upload_failures: int = 0
        self.last_failure_reason: Optional[str] = None

    def to_dict(self) -> dict:
        """
        Serialize the document requirement into a dictionary representation.

        Role & Interconnections:
            Called by `ApplicationSession.to_dict()` and `CollectionAgent._persist_session()`
            to prepare JSON payloads for the database repository (`Repository.save_collection_session`)
            and REST responses in `app/routes/collection.py`.

        Returns:
            dict: Dictionary containing document requirement state and extraction metadata.
        """
        return {
            "doc_type": self.doc_type,
            "mandatory": self.mandatory,
            "submitted": self.submitted,
            "submitted_file_id": self.submitted_file_id,
            "extraction_ok": self.extraction_ok,
            "extraction_confidence": self.extraction_confidence,
            "upload_failures": self.upload_failures,
            "last_failure_reason": self.last_failure_reason,
        }


class ApplicationSession:
    """
    Represents a user's application session, tracking what has been
    collected and what remains.

    Responsibility:
    ---------------
    Manages session-level state transitions ('collecting', 'incomplete', 'complete', 'interrupted',
    'exception'), coordinates multiple `DocumentRequirement` objects, monitors overall completeness,
    and produces user-friendly status updates.

    State Attributes:
    -----------------
    session_id (str): Unique UUID string identifying this collection session.
    user_id (str): ID of the user owning the session.
    service_id (str): Identifier of the government or corporate service being applied for.
    service_name (str): Human-readable name of the target service.
    service_description (str): Description of the target service.
    processing_time (str): Expected processing duration (e.g., '2 business days').
    created_at (datetime): Timestamp when the session was created.
    last_updated (datetime): Timestamp when the session was last modified.
    status (str): Current lifecycle state ('collecting', 'incomplete', 'complete', 'interrupted', 'exception').
    document_requirements (Dict[str, DocumentRequirement]): Mapping of document type to its requirement tracker.
    submitted_file_ids (List[str]): List of all file IDs successfully accepted during this session.
    conversation_history (List[dict]): Log of chat dialogue turns related to this collection session.
    notes (List[str]): Internal lifecycle and operational audit notes.

    Interconnections:
    -----------------
    Instantiated and managed by `CollectionAgent`. Persisted to PostgreSQL (`collection_sessions` table)
    via `CollectionAgent._persist_session` and `Repository.save_collection_session`.
    Used by `app/routes/collection.py` and `app/routes/chat.py` to drive conversational collection flows.
    """

    def __init__(self, session_id: str, user_id: str, service_id: str):
        """
        Initialize an application session.

        Args:
            session_id (str): Unique UUID string identifying the session.
            user_id (str): User identifier who owns this application.
            service_id (str): Service identifier from the service catalogue.
        """
        self.session_id = session_id
        self.user_id = user_id
        self.service_id = service_id
        self.service_name: str = ""
        self.service_description: str = ""
        self.processing_time: str = ""
        self.created_at: datetime = datetime.now(timezone.utc)
        self.last_updated: datetime = datetime.now(timezone.utc)
        self.status: str = "collecting"  # collecting, incomplete, complete, interrupted, exception
        self.document_requirements: Dict[str, DocumentRequirement] = {}
        self.submitted_file_ids: List[str] = []
        self.conversation_history: List[dict] = []
        self.notes: List[str] = []

    def add_document_requirement(self, doc_type: str, mandatory: bool = True):
        """
        Add a document requirement for this application.

        Role & Interconnections:
            Called during `CollectionAgent.create_session()` when registering mandatory
            or optional documents defined in the service catalogue.

        Args:
            doc_type (str): Unique document category key (e.g. 'passport', 'national_id').
            mandatory (bool, optional): Whether submission is mandatory. Defaults to True.
        """
        self.document_requirements[doc_type] = DocumentRequirement(doc_type, mandatory)

    def get_next_required_document(self) -> Optional[str]:
        """
        Determine the next document to ask for.

        Design Decision:
            Asks for the first missing mandatory document, then any missing optional
            documents. This avoids asking the user to guess which document they should upload next.

        Role & Interconnections:
            Called by `get_status_message()` and `CollectionAgent._suggest_next()` to form
            actionable guidance sent to chat users in `app/routes/chat.py` and `app/routes/collection.py`.

        Returns:
            Optional[str]: Name of the next missing document type, or None if all are submitted.
        """
        # First, mandatory missing
        for doc_type, req in self.document_requirements.items():
            if req.mandatory and not req.submitted:
                return doc_type

        # Then optional
        for doc_type, req in self.document_requirements.items():
            if not req.submitted:
                return doc_type

        return None

    def mark_document_submitted(self, doc_type: str, file_id: str,
                                 extraction_ok: bool = True,
                                 extraction_fields: Dict = None,
                                 extraction_confidence: float = 0.0):
        """
        Mark a document as submitted with extraction results.

        Role & Interconnections:
            Called by `CollectionAgent.submit_document()` when a document upload has been
            accepted. Updates the slot's `DocumentRequirement` instance and records the `file_id`.

        Args:
            doc_type (str): Document category key.
            file_id (str): Storage identifier for the uploaded file.
            extraction_ok (bool, optional): Whether extraction succeeded. Defaults to True.
            extraction_fields (Dict, optional): Structured fields extracted from the file. Defaults to None.
            extraction_confidence (float, optional): Aggregate extraction confidence score. Defaults to 0.0.
        """
        if doc_type in self.document_requirements:
            req = self.document_requirements[doc_type]
            req.submitted = True
            req.submitted_file_id = file_id
            req.submitted_at = datetime.now(timezone.utc)
            req.extraction_ok = extraction_ok
            req.extraction_fields = extraction_fields or {}
            req.extraction_confidence = extraction_confidence
            if file_id not in self.submitted_file_ids:
                self.submitted_file_ids.append(file_id)

        self.last_updated = _utcnow()

    def record_upload_failure(self, doc_type: str, reason: str):
        """
        Record an upload failure and reason.

        Role & Interconnections:
            Called by `CollectionAgent.submit_document()` when an upload or extraction fails.
            Increments the failure counter used for retry thresholds and escalation triggers.

        Args:
            doc_type (str): Document category key that failed.
            reason (str): Human-readable or error diagnostic reason.
        """
        if doc_type in self.document_requirements:
            req = self.document_requirements[doc_type]
            req.upload_failures += 1
            req.last_failure_reason = reason
            self.last_updated = _utcnow()

    def check_completeness(self) -> Tuple[bool, List[str]]:
        """
        Check if all required documents have been submitted.

        Role & Interconnections:
            Called by `is_ready_for_validation()` and `CollectionAgent.submit_document()`
            to determine whether the application can transition to validation or review.

        Returns:
            Tuple[bool, List[str]]:
                - is_complete (bool): True if all mandatory documents have been submitted.
                - missing (List[str]): List of doc_types that are still unsubmitted.
        """
        missing = []
        for doc_type, req in self.document_requirements.items():
            if req.mandatory and not req.submitted:
                missing.append(doc_type)

        return (len(missing) == 0, missing)

    def get_required_count(self) -> int:
        """
        Get total number of required documents (immutable).

        Returns:
            int: Total count of required document slots configured for this session.
        """
        return len(self.document_requirements)

    def get_submitted_count(self) -> int:
        """
        Get number of submitted documents.

        Returns:
            int: Count of document requirements where `submitted == True`.
        """
        return sum(1 for r in self.document_requirements.values() if r.submitted)

    def is_ready_for_validation(self) -> bool:
        """
        Check if the application has all required documents and is ready for validation.

        Role & Interconnections:
            Verifies both submission completeness and that extracted documents are readable
            (`extraction_ok == True`). Used as a precondition before invoking `ValidationAgent`.

        Returns:
            bool: True if all mandatory documents are submitted and readable, False otherwise.
        """
        complete, _ = self.check_completeness()
        # Also check that extracted documents are readable
        for doc_type, req in self.document_requirements.items():
            if req.submitted and not req.extraction_ok:
                return False
        return complete

    def get_status_message(self) -> str:
        """
        Get a human-readable status message.

        Role & Interconnections:
            Formats an end-user progress message returned by chat and collection endpoints
            in `app/routes/collection.py` and `app/routes/chat.py`.

        Returns:
            str: Human-readable status update summarizing submitted vs required count and next steps.
        """
        if self.status == "complete":
            return "Application complete. Ready for validation."
        elif self.status == "exception":
            return "An issue has occurred. A human validator has been notified."
        elif self.status == "interrupted":
            return "Application paused. You can resume or start over."

        # Count submitted vs total
        total = len(self.document_requirements)
        submitted = sum(1 for r in self.document_requirements.values() if r.submitted)

        if submitted > 0:
            return f"Progress: {submitted}/{total} documents submitted. " \
                   f"Next: please upload {self.get_next_required_document()}."
        else:
            first_req = next(iter(self.document_requirements))
            return f"Please upload your {first_req} to begin."

    def handle_interruption(self):
        """
        Handle a user interrupting mid-submission (e.g., asks a question or changes service).

        Role & Interconnections:
            Sets status to 'interrupted' and appends an audit note. Called by
            `CollectionAgent.handle_service_change()` or when a new session replaces an active one.
        """
        self.status = "interrupted"
        self.notes.append(f"Session interrupted at {_utcnow().isoformat()}")

    def resume(self):
        """
        Resume an interrupted session.

        Role & Interconnections:
            Transitions status back to 'collecting' and logs a resume note, allowing
            a previously paused collection workflow to continue seamlessly.
        """
        self.status = "collecting"
        self.notes.append(f"Session resumed at {_utcnow().isoformat()}")

    def to_dict(self) -> dict:
        """
        Serialize application session to a dictionary.

        Role & Interconnections:
            Provides the dict format stored in PostgreSQL JSON fields via `Repository`
            and returned to HTTP clients by API endpoints in `app/routes/collection.py`.

        Returns:
            dict: Complete session state dictionary including nested document requirements.
        """
        return {
            "session_id": self.session_id,
            "user_id": self.user_id,
            "service_id": self.service_id,
            "service_name": self.service_name,
            "status": self.status,
            "created_at": self.created_at.isoformat(),
            "last_updated": self.last_updated.isoformat(),
            "document_requirements": {k: v.to_dict() for k, v in self.document_requirements.items()},
            "submitted_file_ids": self.submitted_file_ids,
            "notes": self.notes,
        }


class CollectionAgent:
    """
    Collection Agent - Phase 2 & Phase 3

    The agent responsible for collecting a complete submission as a
    reasoning component, not just a script that asks for the next item
    on a list.

    Key capabilities:
    - Works out what documents are required for the chosen service
    - Tracks what has been submitted vs what is still missing
    - Asks for the right thing next
    - Reasons about whether an acceptable alternative exists
    - Works out why an upload went wrong before deciding what to ask
    - Handles interruptions without losing state
    - Persists session state to database via repository layer

    Cross-File Interconnections:
    ----------------------------
    - `app/main.py`: Created at startup and attached to `app_state["collection_agent"]`.
    - `app/routes/applications.py`: Calls `create_session()` during application initiation.
    - `app/routes/collection.py`: Interacts with `get_session()` and `submit_document()`.
    - `app/routes/chat.py`: Reads collection progress to guide chat dialogue.
    - `services/repository.py`: Injected as `self.repository` for PostgreSQL persistence and service lookup.
    """

    def __init__(self, repository=None):
        """
        Initialize the CollectionAgent.

        Args:
            repository (Optional[Repository]): Database repository instance for persisting
                and retrieving collection session state. If None, operates purely in-memory.
        """
        self.sessions: Dict[str, ApplicationSession] = {}
        self.sessions_by_user: Dict[str, str] = {}  # user_id -> active_session_id
        self.repository = repository

    def _persist_session(self, session: ApplicationSession, application_id: str = None):
        """
        Persist current session state to PostgreSQL via repository.

        Cross-File Interconnections:
            Calls `Repository.save_collection_session()` in `services/repository.py`, which
            executes against the `collection_sessions` table via `DatabaseService` in `services/database.py`.

        Args:
            session (ApplicationSession): The active application session instance to persist.
            application_id (Optional[str], optional): Associated application ID if already linked.
        """
        if self.repository:
            self.repository.save_collection_session(
                session_id=session.session_id,
                user_id=session.user_id,
                service_id=session.service_id,
                service_name=session.service_name,
                status=session.status,
                document_requirements={k: v.to_dict() for k, v in session.document_requirements.items()},
                submitted_file_ids=session.submitted_file_ids,
                application_id=application_id,
                conversation_history=session.conversation_history,
                notes=session.notes,
            )

    def _restore_session(self, session_id: str, user_id: str) -> Optional[ApplicationSession]:
        """
        Restore a CollectionAgent session from PostgreSQL.

        Cross-File Interconnections:
            Calls `Repository.get_collection_session(session_id, user_id)` in `services/repository.py`
            to retrieve serialized state from PostgreSQL and reconstruct `ApplicationSession`
            and `DocumentRequirement` objects in memory.

        Args:
            session_id (str): Unique identifier of the session to restore.
            user_id (str): User identifier to verify authorization and ownership.

        Returns:
            Optional[ApplicationSession]: Reconstituted ApplicationSession instance, or None if not found.
        """
        if not self.repository:
            return None
        data = self.repository.get_collection_session(session_id, user_id)
        if not data:
            return None
        session = ApplicationSession(
            session_id=session_id,
            user_id=user_id,
            service_id=data.get("service_id", ""),
        )
        session.service_name = data.get("service_name", "")
        session.status = data.get("status", "collecting")
        doc_reqs = data.get("document_requirements", {})
        for doc_type, req_data in doc_reqs.items():
            req = DocumentRequirement(doc_type, mandatory=req_data.get("mandatory", True))
            req.submitted = req_data.get("submitted", False)
            req.submitted_file_id = req_data.get("submitted_file_id")
            req.submitted_at = req_data.get("submitted_at")
            if req.submitted_at and isinstance(req.submitted_at, str):
                from datetime import datetime, timezone
                req.submitted_at = datetime.fromisoformat(req.submitted_at)
            req.extraction_ok = req_data.get("extraction_ok", False)
            req.extraction_fields = req_data.get("extraction_fields", {})
            req.extraction_confidence = req_data.get("extraction_confidence", 0.0)
            req.upload_failures = req_data.get("upload_failures", 0)
            req.last_failure_reason = req_data.get("last_failure_reason")
            session.document_requirements[doc_type] = req
        session.submitted_file_ids = data.get("submitted_file_ids", [])
        session.conversation_history = data.get("conversation_history", [])
        session.notes = data.get("notes", [])
        return session

    def create_session(self, user_id: str, service_id: str,
                       service_name: str = "", service_description: str = "",
                       processing_time: str = "",
                       required_documents: List[str] = None,
                       allowed_alternatives: Dict = None) -> str:
        """
        Create a new application session for a user.

        Role & Cross-File Interconnections:
            Called by `app/routes/applications.py` (`create_application` endpoint) when an applicant
            chooses a service. Loads document requirements from the service catalogue, handles
            any previous active session for the user by marking it interrupted, saves the new
            session to database via `_persist_session()`, and returns the `session_id`.

        Args:
            user_id (str): User identifier.
            service_id (str): Service ID (e.g. 'standard_passport_renewal').
            service_name (str, optional): Display name of the service. Defaults to "".
            service_description (str, optional): Description of the service. Defaults to "".
            processing_time (str, optional): Service turnaround SLA string. Defaults to "".
            required_documents (List[str], optional): List of required document types. Defaults to None.
            allowed_alternatives (Dict, optional): Dictionary mapping doc_types to acceptable alternatives. Defaults to None.

        Returns:
            str: Newly generated UUID session_id.
        """
        session_id = str(uuid.uuid4())

        session = ApplicationSession(session_id, user_id, service_id)
        session.service_name = service_name
        session.service_description = service_description
        session.processing_time = processing_time

        # Store immutable requirements from catalogue
        if required_documents:
            for doc_type in required_documents:
                session.add_document_requirement(doc_type, mandatory=True)

        # Track as active session for this user
        if user_id in self.sessions_by_user:
            prev_id = self.sessions_by_user[user_id]
            if prev_id in self.sessions:
                prev = self.sessions[prev_id]
                prev.handle_interruption()

        self.sessions[session_id] = session
        self.sessions_by_user[user_id] = session_id

        # Persist new session to database
        self._persist_session(session)

        return session_id

    def get_session(self, session_id: str, user_id: str = None) -> Optional[ApplicationSession]:
        """
        Get a session by ID. If user_id provided, verify ownership.

        Role & Cross-File Interconnections:
            Called by route handlers in `app/routes/collection.py`, `app/routes/applications.py`,
            and `app/routes/chat.py` to inspect current collection status and validate user ownership.

        Args:
            session_id (str): Session UUID string.
            user_id (Optional[str], optional): Expected user ID to verify access rights. Defaults to None.

        Returns:
            Optional[ApplicationSession]: Matching ApplicationSession if found and authorized, else None.
        """
        session = self.sessions.get(session_id)
        if session and user_id and session.user_id != user_id:
            return None
        return session

    def get_user_active_session(self, user_id: str) -> Optional[ApplicationSession]:
        """
        Get the active session for a user.

        Role & Cross-File Interconnections:
            Called by `app/routes/chat.py` (`/chat/wizard`) and `handle_service_change()` to locate
            the user's ongoing session without requiring the client to pass session_id explicitly.

        Args:
            user_id (str): User identifier.

        Returns:
            Optional[ApplicationSession]: Active session if one exists, else None.
        """
        session_id = self.sessions_by_user.get(user_id)
        if session_id:
            return self.sessions.get(session_id)
        return None

    def submit_document(self, session_id: str, doc_type: str, file_id: str,
                        extraction_ok: bool = True,
                        extraction_fields: Dict = None,
                        extraction_confidence: float = 0.0) -> Dict:
        """
        Submit a document for a session and process it.

        Workflow & Decision Logic:
        --------------------------
        1. Validates that the session exists; returns error action if missing.
        2. Validates doc_type against service requirements; rejects with available options if invalid.
        3. Checks duplicate submissions and checks `repository.get_service()` for allowed alternatives.
        4. If extraction_ok:
           - Marks requirement submitted and records fields/confidence.
           - Persists session to database.
           - Checks overall completeness via `check_completeness()`.
           - If complete and all readable -> status = 'complete', ready for ValidationAgent.
           - If complete but unreadable items exist -> status = 'incomplete', needs review.
           - If incomplete -> suggests next required document.
        5. If extraction failed:
           - Records failure reason and increments attempt counter.
           - If failure count >= 2 -> escalates to validation ('exception' state).
           - Otherwise, instructs user to retry with clearer photography instructions.

        Cross-File Interconnections:
        ----------------------------
        Called by `collection_submit` route in `app/routes/collection.py` after document uploads
        and extraction pipeline execution. Integrates with `Repository.get_service()` and
        persists status via `_persist_session()`.

        Args:
            session_id (str): Application session ID.
            doc_type (str): Document category (e.g., 'passport').
            file_id (str): Storage UUID/ID referencing the document file.
            extraction_ok (bool, optional): Whether extraction succeeded. Defaults to True.
            extraction_fields (Dict, optional): Extracted field attributes. Defaults to None.
            extraction_confidence (float, optional): Model confidence score. Defaults to 0.0.

        Returns:
            Dict: Action dictionary containing outcome ('complete', 'continue', 'retry',
                  'needs_review', 'escalate_to_validation', 'rejected_wrong_type', 'rejected_duplicate')
                  along with user message and next guidance.
        """
        session = self.get_session(session_id)
        if not session:
            return {"error": "Session not found", "action": "error"}

        # Check if this document type is required for this service
        if doc_type not in session.document_requirements:
            # Maybe it's an alternative?
            service_id = session.service_id
            # We'll handle this in the routing layer
            return {
                "error": f"Document type '{doc_type}' is not a valid document for {session.service_name}",
                "action": "rejected_wrong_type",
                "message": f"This service requires: {', '.join(session.document_requirements.keys())}"
            }

        req = session.document_requirements[doc_type]

        # Phase 3: Check for alternatives — if doc_type is already submitted,
        # check if service accepts an alternative document
        if req.submitted:
            service_def = None
            if self.repository:
                # Try to get service definition to check allowed_alternatives
                service_def = self.repository.get_service(session.service_id)
            if service_def:
                alternatives = service_def.get("allowed_alternatives", {})
                # If this document type has alternatives, check if user is submitting
                # a valid alternative
                alt_docs = alternatives.get(doc_type, [])
                if alt_docs and file_id in req.submitted_file_id:
                    return {
                        "action": "rejected_duplicate",
                        "message": f"You have already uploaded a {doc_type}. "
                                   f"Alternatives accepted for this slot: {', '.join(alt_docs)}"
                    }
            return {
                "action": "rejected_duplicate",
                "message": f"You have already uploaded a {doc_type}. Uploading the same document twice is not allowed."
            }

        if extraction_ok:
            session.mark_document_submitted(
                doc_type, file_id, extraction_ok, extraction_fields, extraction_confidence
            )

            # Persist after document submission
            self._persist_session(session, application_id=session_id)  # application_id tied later

            # Check if application is now complete
            is_complete, missing = session.check_completeness()
            if is_complete:
                all_ok = all(r.extraction_ok for r in session.document_requirements.values())
                if all_ok:
                    session.status = "complete"
                else:
                    # Some documents failed extraction
                    session.status = "incomplete"
                    failed = [dt for dt, r in session.document_requirements.items()
                              if not r.extraction_ok]
                # Persist final state
                self._persist_session(session)
                if all_ok:
                    return {
                        "action": "complete",
                        "message": f"All required documents submitted for {session.service_name}. "
                                   f"Your application is ready for validation."
                    }
                else:
                    return {
                        "action": "needs_review",
                        "message": f"All documents received but some need human review due to extraction issues: {', '.join(failed)}"
                    }
            else:
                next_doc = self._suggest_next(session)
                return {
                    "action": "continue",
                    "message": f"Successfully uploaded {doc_type}. {session.get_status_message()}",
                    "next": next_doc
                }
        else:
            # Extraction failed
            session.record_upload_failure(doc_type, "Extraction failed")

            # Check if we've exceeded retry limit
            if req.upload_failures >= 2:
                # Hand off to validation agent
                session.status = "exception"
                return {
                    "action": "escalate_to_validation",
                    "message": f"The {doc_type} could not be read clearly after multiple attempts. "
                                f"I will escalate this to a human validator."
                }

            return {
                "action": "retry",
                "message": f"The {doc_type} image is not clear enough. Please try again with a "
                           f"clearer photo. Make sure the entire document is visible and not blurry.",
                "suggestion": f"Ensure the document is flat on a table, well-lit, and all corners are visible."
            }

    def handle_question(self, session_id: str, question: str) -> Dict:
        """
        Handle a user asking a question during submission.

        The session is NOT interrupted - we answer the question and
        return to the collection flow.

        Role & Cross-File Interconnections:
            Called during wizard chat processing in `app/routes/chat.py` when an FAQ query
            is intercepted mid-collection, allowing FAQ answers from `GenerationService` / `PolicyService`
            while preserving active collection progress.

        Args:
            session_id (str): Session identifier.
            question (str): The user's question text.

        Returns:
            Dict: Action response with 'answer_question' status and current application progress.
        """
        session = self.get_session(session_id)
        if not session:
            return {"error": "Session not found"}

        session.notes.append(f"Question asked during collection: {question}")

        # For now, return a placeholder - the actual FAQ answer comes from
        # the service catalogue + generation service
        return {
            "action": "answer_question",
            "session_id": session_id,
            "message": f"I've noted your question: '{question}'. "
                       f"Meanwhile, your application status: {session.get_status_message()}"
        }

    def handle_service_change(self, user_id: str, new_service_id: str) -> Dict:
        """
        Handle a user switching services mid-conversation.

        Design Rule:
            Documents already uploaded must NOT attach to the wrong service.
            The current active session is safely marked 'interrupted' and persisted to database.

        Role & Cross-File Interconnections:
            Called by `app/routes/chat.py` or `app/routes/applications.py` when an applicant
            pivots to a different service during intake.

        Args:
            user_id (str): User identifier.
            new_service_id (str): Target service ID being switched to.

        Returns:
            Dict: Action response detailing previous session pause and readiness for new service.
        """
        current = self.get_user_active_session(user_id)
        if current:
            current.handle_interruption()
            current.notes.append(f"User switched service from {current.service_id} to {new_service_id}")
            # Persist interrupted session
            self._persist_session(current)

        return {
            "action": "service_changed",
            "old_session_status": "interrupted" if current else None,
            "message": f"Your previous application for {current.service_name if current else 'the previous service'} has been paused. "
                       f"Starting a new application for the new service."
        }

    def _suggest_next(self, session: ApplicationSession) -> str:
        """
        Suggest the next document to ask for.

        Internal helper called by `submit_document()` to craft the next prompt.

        Args:
            session (ApplicationSession): The active application session.

        Returns:
            str: Directional message specifying the next document to upload.
        """
        next_doc = session.get_next_required_document()
        if next_doc:
            return f"Please upload your {next_doc}."
        return "All required documents collected!"

    def reason_about_upload_failure(self, session_id: str, file_type: str,
                                     extraction_result: Dict) -> str:
        """
        Reason about why an upload went wrong and give specific advice.

        Design Decision:
            Categorizes failures into distinct types so the agent can give specific,
            helpful responses instead of generic "try again" messages.

        Role & Cross-File Interconnections:
            Called when handling low-confidence or rejected extractions to produce
            tailored diagnostic guidance before asking the user for re-upload.

        Args:
            session_id (str): Session identifier.
            file_type (str): Detected MIME or file category string.
            extraction_result (Dict): Dictionary containing extraction confidence and raw text.

        Returns:
            str: Diagnostic explanation and user advice.
        """
        session = self.get_session(session_id)
        if not session:
            return "Session not found."

        doc_type = self._get_document_type_for_upload(session, file_type)

        # Wrong document type entirely
        if doc_type and doc_type not in session.document_requirements:
            return (f"That is not the correct document type. "
                    f"Please upload a {', '.join(session.document_requirements.keys())}.")

        # Right type but unclear image
        if extraction_result.get("confidence", 1.0) < 0.5:
            return (f"The image quality is too low to read the {doc_type}. "
                    f"Please retake the photo ensuring the document is flat, "
                    f"well-lit, and all text is clearly visible.")

        # Document is corrupted or unreadable
        if extraction_result.get("extracted_text") == "":
            return (f"The uploaded file appears to be corrupted or empty. "
                    f"Please try uploading a different file.")

        return "Unknown error with the upload."

