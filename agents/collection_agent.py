    def remove_session(self, session_id: str, user_id: str) -> bool:
        """
        Remove a session, verifying ownership.

        Role & Cross-File Interconnections:
            Called during session cancellation or cleanup routes in `app/routes/collection.py`.

        Args:
            session_id (str): Session UUID string.
            user_id (str): User identifier to verify authorization.

        Returns:
            bool: True if removed successfully, False if session not found or unauthorized.
        """
        session = self.sessions.get(session_id)
        if session and session.user_id == user_id:
            del self.sessions[session_id]
            if self.sessions_by_user.get(user_id) == session_id:
                del self.sessions_by_user[user_id]
            return True
        return False
