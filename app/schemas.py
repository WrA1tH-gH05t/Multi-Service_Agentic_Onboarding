"""
Data transfer and schema definitions for the Multi-Service Agentic Onboarding system.

Module Purpose & Role in the Project:
-------------------------------------
This module centralizes all Pydantic models (data schemas) used across FastAPI
endpoints and internal services for validating request payloads and structuring
response bodies. It enforces type safety, field serialization, and validation constraints
across the API surface.

Interconnections with Other Files:
-----------------------------------
- Used by route modules in `app/routes/`:
  * `app/routes/auth.py`: Uses `AuthenticationRequest`, `UserRegistrationRequest`, `TokenResponse`.
  * `app/routes/services.py`: Implements structures aligned with `ServiceCatalogResponse` & `ServiceCatalogItem`.
  * `app/routes/chat_message.py` & `app/routes/chat.py`: Use `ChatMessage` and `ChatResponse`.
  * `app/routes/documents.py`: Uses `UploadResponse` and `ExtractionResult`.
  * `app/routes/applications.py`: Uses `ApplicationCreate` and `ApplicationResponse`.
  * `app/routes/validation.py`: Uses `ValidationRequest`, `ValidationResult`, `FAQRequest`, `FAQResponse`.
  * `app/routes/golden.py`: Uses `GoldenDatasetValidationRequest`, `GoldenDatasetSearchRequest`.
- Bridges HTTP payloads with core backend domain entities in `services/` and `agents/`.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class UploadResponse(BaseModel):
    """
    Response schema returned after uploading a document.

    Attributes:
        file_id (str): Unique identifier assigned to the stored or processed file.
        filename (str): Sanitized original file name.
        size (int): Size of uploaded content in bytes.
        status (str): Current processing state (e.g. 'processed', 'already_exists', 'pending').

    Interconnections:
        - Returned by document upload routes in `app/routes/documents.py` to the frontend client.
        - Relates to underlying records in `services.database.Document`.
    """
    file_id: str
    filename: str
    size: int
    status: str


class ExtractionResult(BaseModel):
    """
    Schema representing structured data extracted from an uploaded document.

    Attributes:
        file_id (str): Associated file or document identifier.
        document_type (str): Classification of document (e.g., 'national_id', 'passport', 'driving_license').
        fields (Dict[str, Any]): Key-value mapping of extracted fields (e.g., full_name, expiry_date, dob).
        confidence (float): Calculated extraction completeness or confidence ratio (0.0 to 1.0).
        status (str): Processing status of extraction ('processed', 'failed', 'review_required').

    Interconnections:
        - Generated by vision AI models in `services.generation.GenerationService` via OCR/vision processing.
        - Consumed by `app/routes/documents.py` and wizard workflows in `app/routes/wizard.py`.
    """
    file_id: str
    document_type: str
    fields: Dict[str, Any]
    confidence: float
    status: str


class ApplicationCreate(BaseModel):
    """
    Request schema for instantiating a new service onboarding application.

    Attributes:
        service_id (str): Identifier of targeted onboarding service (e.g., 'basic_registration').
        applicant_name (str): Full legal name of applicant.
        applicant_email (str): Contact email address for status notifications.
        documents (List[str]): List of pre-uploaded document IDs associated with this application.

    Interconnections:
        - Handled by `app/routes/applications.py:create_application`.
        - Persisted into `services.database.Application` through `services.repository.Repository`.
    """
    service_id: str
    applicant_name: str
    applicant_email: str
    documents: List[str]


class ApplicationResponse(BaseModel):
    """
    Response schema returning application details and current processing state.

    Attributes:
        application_id (str): Unique identifier of the onboarding application.
        service_id (str): Onboarding service catalog identifier.
        applicant_name (str): Name of the applicant.
        status (str): Lifecycle status (e.g., 'incomplete', 'processing', 'complete', 'needs_review').
        extracted_data (Optional[Dict[str, Any]]): Aggregated document fields or validation summary.

    Interconnections:
        - Returned by `app/routes/applications.py` endpoints to frontend tracking dashboards.
    """
    application_id: str
    service_id: str
    applicant_name: str
    status: str
    extracted_data: Optional[Dict[str, Any]] = None


class AuthenticationRequest(BaseModel):
    """
    Request schema for user authentication.

    Attributes:
        username (str): Registered username or email.
        password (str): Plaintext password supplied for credential verification.

    Interconnections:
        - Consumed by `app/routes/auth.py:login`.
        - Verified by `services.auth.AuthService:authenticate`.
    """
    username: str
    password: str


class TokenResponse(BaseModel):
    """
    Response schema returning a session authentication token and user profile metadata.

    Attributes:
        token (str): Bearer session token string.
        user_id (str): Unique user identifier.
        email (str): Primary user email address.

    Interconnections:
        - Produced by `app/routes/auth.py:login` and registration routes.
        - Token stored client-side in browser session/local storage for subsequent requests.
    """
    token: str
    user_id: str
    email: str


class UserRegistrationRequest(BaseModel):
    """
    Request schema for creating a new user account.

    Attributes:
        username (str): Desired username.
        password (str): Plaintext password for new account.
        email (Optional[str]): Optional user email address; defaults to username if omitted.
        name (str): Display or full name of the user.

    Interconnections:
        - Consumed by `app/routes/auth.py:register` and `app/routes/auth.py:signup`.
        - Persisted to database table `users` (`services.database.User`) and `services/auth_users.json`.
    """
    username: str
    password: str
    email: Optional[str] = ""
    name: str = ""


class FAQRequest(BaseModel):
    """
    Request schema for querying the system FAQ / policy assistance.

    Attributes:
        question (str): Natural language inquiry asked by the user.
        context (Optional[str]): Optional additional contextual information or conversation history.

    Interconnections:
        - Consumed by `app/routes/validation.py:query_faq`.
        - Matched against policies using `services.policy_service.get_grounding_context`.
    """
    question: str
    context: Optional[str] = None


class FAQResponse(BaseModel):
    """
    Response schema returning grounded FAQ answers and citations.

    Attributes:
        answer (str): Answer synthesized or retrieved from policy knowledge.
        sources (List[Dict[str, Any]]): Policy documents or references that ground the answer.
        confidence (float): Match confidence score from catalog or vector retrieval.

    Interconnections:
        - Returned by `app/routes/validation.py:query_faq` to client chat/help widgets.
    """
    answer: str
    sources: List[Dict[str, Any]]
    confidence: float


class ValidationRequest(BaseModel):
    """
    Request schema for standalone or application document validation.

    Attributes:
        application_id (str): Identifier of the application or test pair being evaluated.
        validation_type (str): Type of validation routine to execute (default: 'document').
        documents (Optional[List[Dict[str, Any]]]): Optional explicit list of document payloads.
        entry_id (Optional[str]): Optional golden dataset entry ID for benchmark validation.

    Interconnections:
        - Dispatched to `app/routes/validation.py:validate_application`.
        - Processed by `agents.validation_agent.ValidationAgent:validate_application`.
    """
    application_id: str
    validation_type: str = "document"
    documents: Optional[List[Dict[str, Any]]] = None
    entry_id: Optional[str] = None


class ValidationResult(BaseModel):
    """
    Response schema summarizing document and cross-document validation checks.

    Attributes:
        application_id (str): Associated application identifier.
        passed (bool): Overall boolean determination (True if all critical checks pass).
        checks (List[Dict[str, Any]]): Granular list of individual verification checks.
        recommendations (List[str]): Suggested remediation actions for rejected fields.

    Interconnections:
        - Returned by `app/routes/validation.py` and converted from `agents.validation_agent.ValidationReport`.
    """
    application_id: str
    passed: bool
    checks: List[Dict[str, Any]]
    recommendations: List[str]


class ServiceCatalogItem(BaseModel):
    """
    Schema describing an onboarding service offered in the system catalog.

    Attributes:
        id (str): Service key (e.g. 'basic_registration', 'premium_crossborder').
        name (str): Human-readable display title.
        description (str): Detailed overview of the service offering.
        required_documents (List[str]): List of mandatory document types required.
        status (str): Availability state ('available' or 'coming_soon').
        fields (Dict[str, str]): Key-value specification of expected data fields.

    Interconnections:
        - Generated by `services.service_catalog.ServiceCatalogService`.
        - Embedded within `ServiceCatalogResponse`.
    """
    id: str
    name: str
    description: str
    required_documents: List[str]
    status: str  # "available" or "coming_soon"
    fields: Dict[str, str]


class ServiceCatalogResponse(BaseModel):
    """
    Response schema providing the full directory of onboarding services.

    Attributes:
        services (List[ServiceCatalogItem]): Currently available onboarding services.
        coming_soon (List[ServiceCatalogItem]): Future services listed for user visibility.

    Interconnections:
        - Consumed by client service discovery views and wizard selectors.
    """
    services: List[ServiceCatalogItem]
    coming_soon: List[ServiceCatalogItem]


class ChatMessage(BaseModel):
    """
    Request schema for user interaction with conversational AI agents.

    Attributes:
        query (str): The natural language query or message prompt from the user.
        context_limit (int): Maximum count of prior turns or grounding items to incorporate.
        token (Optional[str]): User session authentication token for security and personalization.

    Interconnections:
        - Handled by `app/routes/chat_message.py:chat`.
        - Grounded via `services.policy_service.get_grounding_context` and processed by
          `services.generation.GenerationService`.
        - Saved to audit database using `services.database.DatabaseService.save_chat_message`.
    """
    query: str
    context_limit: int = 5
    token: Optional[str] = None


class ChatResponse(BaseModel):
    """
    Response schema returning synthesized assistant reply and conversational intent.

    Attributes:
        response (str): The assistant's conversational response.
        sources (List[Dict[str, Any]]): Policy documents or catalog items used for grounding.
        confidence (float): Confidence score of intent classification and answer generation.
        intent (Optional[str]): Detected conversational intent (e.g. 'apply', 'faq', 'blocked_injection').
        matched_service (Optional[str]): Identified service identifier if service intent is present.

    Interconnections:
        - Returned by `app/routes/chat_message.py:chat`.
        - Drives client frontend navigation (e.g., redirecting to wizard when intent is 'apply').
    """
    response: str
    sources: List[Dict[str, Any]]
    confidence: float
    intent: Optional[str] = None
    matched_service: Optional[str] = None


class DocumentMatch(BaseModel):
    """
    Schema recording matching outcome between two documents (e.g., Identity vs Passport).

    Attributes:
        document_id (str): Target document identifier evaluated.
        match_confidence (float): Metric of match degree across compared identity attributes.
        matched_fields (List[str]): List of fields where values matched across documents.
        mismatches (List[str]): List of fields where values conflicted or differed.

    Interconnections:
        - Used during cross-document validation in `agents.validation_agent.ValidationAgent`.
    """
    document_id: str
    match_confidence: float
    matched_fields: List[str]
    mismatches: List[str]


class GoldenDatasetValidationRequest(BaseModel):
    """
    Request body for validating an extraction against the golden dataset.

    Attributes:
        entry_id (str): The golden ground truth record identifier.
        fields (Dict[str, str]): Extracted field key-value pairs being evaluated.

    Interconnections:
        - Dispatched to `app/routes/golden.py:validate_extraction`.
        - Validated by `services.golden_dataset.GoldenDatasetService:validate_extraction`.
    """
    entry_id: str
    fields: Dict[str, str]


class GoldenDatasetSearchRequest(BaseModel):
    """
    Request body for searching the golden dataset.

    Attributes:
        query (str): Keyword query terms to search against ground truth records.
        limit (int): Pagination constraint on returned records (between 1 and 50).

    Interconnections:
        - Handled in `app/routes/golden.py:search_golden_dataset`.
        - Executes search on `services.golden_dataset.GoldenDatasetService:search`.
    """
    query: str
    limit: int = Field(default=10, ge=1, le=50)
